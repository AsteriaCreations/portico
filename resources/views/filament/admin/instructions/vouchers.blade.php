<x-screen-instructions title="How to use Vouchers">
    <p>An append-only account-credit ledger — every row here is a real event: a voucher issued, or spent at check-in. There is no edit or delete for anyone, ever.</p>
    <p>To fix a mistake, issue an offsetting row (a negative amount cancels a prior grant) rather than trying to change the original — that keeps the ledger an honest record of what actually happened.</p>
    <p>Manager+ can view this list; only Admin+ can issue a new voucher.</p>
</x-screen-instructions>
