<x-screen-instructions title="How to use Categories">
    <p>Member categories — freely editable, with one exception: <strong>Prospective</strong>, <strong>Guest</strong>, and <strong>Irregular</strong> can't be renamed or deleted, because other parts of the app look them up by that exact name.</p>
    <p>Everything else about the list — adding a category, reordering, deactivating one — is unrestricted.</p>
</x-screen-instructions>
